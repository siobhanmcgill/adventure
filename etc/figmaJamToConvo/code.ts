// TODO: figure out how to include these as types without compiling everything
const FLAG_DELIMITERS = ['##', '#', '>', '@', '.', '$'];
type Quote = string | string[];

type ConvoFlagDelimiter = typeof FLAG_DELIMITERS[number];

type ConvoFlagKey<K extends string> =
  | `${K}${ConvoFlagDelimiter}${string}`
  // For a quest phase (somestep$quest:phase2)
  | `${K}$${string}:${string}`
  // For a previous conversation step.
  | `${string}>${K}`;

interface ConvoResponseOption {
  // A conversation flag to determine if this option is available
  condition?: ConvoFlagKey<''>;
  text: string;
  // Optionally trigger some sort of more granular action.
  action?: Action;
  // goto: 'something' continues the convo at the something path
  goto?: string;
  // Include a conversation flag to trigger a goto under different circumstances
  // FIXME: This may or may not work or be useful
  [gotoWithFlag: ConvoFlagKey<'goto'>]: string;
}

interface ConvoStep {
  text?: Quote;
  responses?: ConvoResponseOption[];
  goto?: string;
  queue?: Quote[];
  onQueueFinishGoto?: string;
  action?: Action;
}

interface Convo {
  [stepName: string | ConvoFlagKey<string>]: ConvoStep;
}

const ui = {
  log: (
    message: string,
    options: Omit<NotificationOptions, 'error'> = {timeout: 2000}
  ) => {
    let n: NotificationHandler;
    const prom = new Promise<NotifyDequeueReason>((res) => {
      n = figma.notify(message, {...options, onDequeue: res});
    }) as Promise<NotifyDequeueReason> & {cancel: () => void};
    prom.cancel = () => {
      n.cancel();
    };
    return prom;
  },
  error: (
    message: string,
    options: Omit<NotificationOptions, 'error' | 'onDequeue'> = {timeout: 2000}
  ) => {
    let n: NotificationHandler;
    const prom = new Promise<NotifyDequeueReason>((res) => {
      n = figma.notify(message, {...options, error: true, onDequeue: res});
    }) as Promise<NotifyDequeueReason> & {cancel: () => void};
    prom.cancel = () => {
      n.cancel();
    };
    return prom;
  },
};

const arrowLike = ['ARROW_LINES', 'ARROW_EQUILATERAL'];
function computeDirectionOfEdge(connector: ConnectorNode) {
  if (arrowLike.includes(connector.connectorEndStrokeCap)) {
    if (arrowLike.includes(connector.connectorStartStrokeCap)) {
      return {directional: 'BI'} as const;
    } else {
      return {
        dir: {
          to: 'connectorEnd',
          from: 'connectorStart',
        },
        directional: 'UNI',
      } as const;
    }
  } else {
    if (arrowLike.includes(connector.connectorStartStrokeCap)) {
      return {
        dir: {
          to: 'connectorStart',
          from: 'connectorEnd',
        },
        directional: 'UNI',
      } as const;
    } else {
      return {directional: 'BI'} as const;
    }
  }
}

